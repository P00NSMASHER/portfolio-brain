"""V7 bounded monitor error isolation and confidential provider diagnostics.

All original events are generated by fake GET transport; there is no
live network, credential use, V6 change, spending, trading or PR merge.
"""
import contextlib
import io
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from brain.__main__ import monitor
from brain.adapters import GitHub
from brain.core import BrainError, Store
from test_brain_investigate import REPO, OTHER, THIRD, REV, SOURCE, Transport

REPOS = [REPO, OTHER, THIRD]
SENTINEL = "PRIVATE_PROVIDER_DIAGNOSTIC_DO_NOT_EMIT"


class ScopedProvider(Transport):
    def __init__(self, fail_repo=REPO, error="SOURCE_API_404", *,
                 all_repos=False, failure_stage="metadata", style="brain"):
        super().__init__()
        self.fail_repo = fail_repo
        self.error = error
        self.all_repos = all_repos
        self.failure_stage = failure_stage
        self.style = style

    def __call__(self, path):
        repo = "/".join(path.split("/")[2:4])
        stage = (
            self.failure_stage == "metadata" and path == "/repos/" + repo
            or self.failure_stage == "checks" and "/check-runs?" in path
            or self.failure_stage == "branch" and "/branches/" in path
        )
        if stage and (repo == self.fail_repo or self.all_repos):
            self.calls.append(path)
            if self.style == "key":
                raise KeyError(SENTINEL)
            if self.style == "unicode":
                raise UnicodeDecodeError("utf-8", b"\xff", 0, 1, SENTINEL)
            raise BrainError(self.error + ": " + SENTINEL)
        return super().__call__(path)


def run_synthetic(provider, *, repos=None, explicit=False, private=False):
    repos = REPOS if repos is None else repos
    api = GitHub(transport=provider, private=private)
    text_out, text_err = io.StringIO(), io.StringIO()
    with tempfile.TemporaryDirectory() as d:
        folder = Path(d)
        store = Store(folder / "original.sqlite",
                      visibility="PRIVATE" if private else "PUBLIC")
        try:
            with patch("brain.__main__.GitHub", return_value=api), \
                 contextlib.redirect_stdout(text_out), \
                 contextlib.redirect_stderr(text_err):
                try:
                    monitor(store, SOURCE, folder / "report",
                            repositories=repos, api=api if explicit else None)
                    outcome = "PASS"
                except BrainError as exc:
                    outcome = str(exc)
            document = json.loads((folder / "report" / "report.json").read_text())
            rows = [json.loads(row["body"]) for row in
                    store.db.execute("SELECT body FROM events ORDER BY seq")]
            attempts = [
                {k: r[k] for k in ("operation", "status", "details")}
                for r in store.db.execute("SELECT * FROM attempts ORDER BY id")
            ]
            return document, rows, provider.calls, api.requests, outcome, \
                text_out.getvalue(), text_err.getvalue(), attempts
        finally:
            store.close()


class PublicMonitorFailureCircuitBreaker(unittest.TestCase):
    def test_one_repo_local_404_continues_to_both_independent_healthy_sources(self):
        report, events, calls, requests, raised, stdout, stderr, attempts = (
            run_synthetic(ScopedProvider()))
        self.assertIn("MONITOR_INCOMPLETE", raised)
        self.assertEqual([e["key"] for e in events], [OTHER, THIRD])
        self.assertEqual(requests, 9)
        self.assertEqual(len(calls), requests)
        self.assertEqual(report["status"], "FAIL")
        operation = report["operation"]
        self.assertEqual(operation["required_repositories"], REPOS)
        self.assertEqual(operation["errors"], [{
            "repository": REPO,
            "error_class": "PUBLIC_MONITOR_EVIDENCE_UNVERIFIED",
            "failure_scope": "REPOSITORY_LOCAL_READ_FAILED",
        }])
        self.assertEqual(operation["deferred_after_global_failure"], [])
        self.assertIs(operation["global_failure_stopped_reads"], False)
        self.assertEqual(attempts[-1]["status"], "FAIL")
        self.assertEqual(report["operation"]["source_revision_rechecks"], [])
        for emitted in (report, stdout, stderr, attempts):
            self.assertNotIn(SENTINEL, str(emitted))
        self.assertEqual(len(events), 2)

    def test_local_middle_repo_does_not_block_third_original_scope(self):
        report, events, calls, requests, *_ = run_synthetic(
            ScopedProvider(fail_repo=OTHER))
        self.assertEqual([item["key"] for item in events], [REPO, THIRD])
        self.assertEqual(requests, 9)
        self.assertEqual(len(calls), 9)
        self.assertEqual(report["operation"]["errors"][0]["repository"], OTHER)
        self.assertEqual(report["status"], "FAIL")

    def test_unknown_and_global_provider_errors_hard_stop_after_first_get(self):
        for error in (
            "SOURCE_API_403", "SOURCE_API_429", "SOURCE_API_500",
            "RATE_LIMIT", "SOURCE_READ_FAILED",
            "PRIVATE_INPUT_REFUSED_BY_PUBLIC_ADAPTER",
            "SOURCE_RETRY_EXHAUSTED", "SOURCE_API_4040",
            "SOME_OTHER_ERROR", "AUTHENTICATION_REQUIRED",
        ):
            with self.subTest(error=error):
                doc, events, calls, requests, raised, stdout, stderr, _ = (
                    run_synthetic(ScopedProvider(error=error)))
                self.assertIn("MONITOR_INCOMPLETE", raised)
                self.assertEqual(requests, 1)
                self.assertEqual(len(calls), 1)
                self.assertEqual(events, [])
                self.assertEqual(doc["operation"]["errors"], [{
                    "repository": REPO,
                    "error_class": "PUBLIC_MONITOR_EVIDENCE_UNVERIFIED",
                    "failure_scope": "GLOBAL_OR_UNCLASSIFIED_SOURCE_STOP",
                }])
                self.assertEqual(doc["operation"]["deferred_after_global_failure"],
                                 [OTHER, THIRD])
                self.assertTrue(doc["operation"]["global_failure_stopped_reads"])
                self.assertNotIn(SENTINEL, stdout + stderr + str(doc))

    def test_local_404_every_repo_has_no_false_complete_source_coverage(self):
        doc, events, calls, requests, _, _, _, _ = run_synthetic(
            ScopedProvider(all_repos=True))
        self.assertEqual(requests, 3)
        self.assertEqual(len(calls), 3)
        self.assertEqual(events, [])
        self.assertEqual(len(doc["operation"]["errors"]), 3)
        self.assertEqual(doc["operation"]["deferred_after_global_failure"], [])
        self.assertFalse(doc["operation"]["global_failure_stopped_reads"])
        self.assertEqual(doc["status"], "FAIL")

    def test_known_source_limited_check_page_unavailable_continues(self):
        doc, events, calls, requests, *_ = run_synthetic(
            ScopedProvider(error="CHECK_COVERAGE_UNAVAILABLE",
                           failure_stage="checks"))
        self.assertEqual(requests, 11)
        self.assertEqual(len(calls), 11)
        self.assertEqual([x["key"] for x in events], [OTHER, THIRD])
        self.assertEqual(doc["operation"]["errors"][0]["failure_scope"],
                         "REPOSITORY_LOCAL_READ_FAILED")

    def test_source_revision_race_retried_once_then_local_failure(self):
        doc, events, calls, requests, *_ = run_synthetic(
            ScopedProvider(error="SOURCE_REVISION_CHANGED",
                           failure_stage="branch"))
        self.assertEqual(requests, 12)
        self.assertEqual(len(calls), 12)
        self.assertEqual([e["key"] for e in events], [OTHER, THIRD])
        self.assertEqual(doc["operation"]["errors"][0]["failure_scope"],
                         "REPOSITORY_LOCAL_READ_FAILED")

    def test_global_failure_at_last_repo_still_records_stop_cause(self):
        doc, events, calls, requests, *_ = run_synthetic(
            ScopedProvider(fail_repo=THIRD,error="SOURCE_API_403"))
        self.assertEqual([e["key"] for e in events], [REPO, OTHER])
        self.assertEqual(requests, 9)
        self.assertEqual(len(calls), 9)
        self.assertEqual(doc["operation"]["deferred_after_global_failure"], [])
        self.assertTrue(doc["operation"]["global_failure_stopped_reads"])

    def test_unclassified_key_and_unicode_exceptions_are_global_stops(self):
        for style in ("key", "unicode"):
            with self.subTest(style=style):
                doc, events, calls, requests, _, stdout, stderr, _ = (
                    run_synthetic(ScopedProvider(style=style)))
                self.assertEqual(len(calls), 1)
                self.assertEqual(requests, 1)
                self.assertEqual(events, [])
                self.assertTrue(doc["operation"]["global_failure_stopped_reads"])
                self.assertNotIn(SENTINEL, str(doc) + stdout + stderr)

    def test_successful_monitor_retains_v6_original_four_gets_per_repository(self):
        provider = Transport()
        doc, events, calls, requests, outcome, *_ = run_synthetic(provider)
        self.assertEqual(outcome, "PASS")
        self.assertEqual(doc["status"], "PASS")
        self.assertEqual(requests, 12)
        self.assertEqual(len(calls), 12)
        self.assertEqual(len(events), 3)
        self.assertEqual(doc["operation"]["errors"], [])
        self.assertEqual(doc["operation"]["source_revision_rechecks"], [])
        self.assertEqual(doc["operation"]["deferred_after_global_failure"], [])
        self.assertFalse(doc["operation"]["global_failure_stopped_reads"])

    def test_explicit_injected_api_preserves_existing_fail_closed_compatibility(self):
        provider = ScopedProvider(error="SOURCE_API_403")
        doc, events, calls, requests, outcome, *_ = run_synthetic(
            provider, explicit=True)
        self.assertIn("MONITOR_INCOMPLETE", outcome)
        self.assertEqual(requests, 9)
        self.assertEqual([x["key"] for x in events], [OTHER, THIRD])
        self.assertNotIn("deferred_after_global_failure", doc["operation"])
        self.assertNotIn("global_failure_stopped_reads", doc["operation"])

    def test_public_quota_remains_twenty_four_gets_maximum(self):
        provider = ScopedProvider(all_repos=True, error="SOURCE_API_404")
        doc, _, _, requests, *_ = run_synthetic(provider)
        self.assertLessEqual(requests, 24)
        self.assertEqual(len(doc["operation"]["errors"]), 3)


if __name__ == "__main__":
    unittest.main()
